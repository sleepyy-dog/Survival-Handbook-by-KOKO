%% Householder-QR Least Squares
function x = lsq_qr_house(A, b)
    [m,n] = size(A);
    d = zeros(n,1);
    for j = 1:n
        [v, beta] = house(A(j:m, j));                   
        A(j:m, j:n) = A(j:m, j:n) - beta * v * (v' * A(j:m, j:n));
        b(j:m)      = b(j:m)      - beta * v * (v' * b(j:m)); 
        d(j) = beta;
        A(j+1:m, j) = v(2:end);                         
    end
    R = triu(A(1:n, 1:n));
    x = R \ b(1:n);                                     
end

%% Algorithm 3.2.1: Householder Transformation
function [v, beta] = house(x)
    n = length(x);
    eta = norm(x, inf);
    if eta == 0
        v = [1; zeros(n-1,1)];
        beta = 0;
        return
    end
    x = x / eta;
    sigma = x(2:n).' * x(2:n);
    v = x;
    if sigma == 0
        beta = 0;
        v(1) = 1;
        return
    end
    alpha = sqrt(x(1)^2 + sigma);
    if x(1) <= 0
        v1 = x(1) - alpha;
    else
        v1 = -sigma / (x(1) + alpha);
    end
    beta = 2 * v1^2 / (sigma + v1^2);
    v = v / v1;
    v(1) = 1;
end
